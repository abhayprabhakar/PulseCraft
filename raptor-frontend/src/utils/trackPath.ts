/**
 * Convert GPS coordinates to normalized coordinates (0-1)
 */
export function gpsToNormalized(coords: GPSCoordinate[]): { x: number; y: number }[] {
    // Find bounds
    const lats = coords.map(c => c.lat);
    const lngs = coords.map(c => c.lng);

    const minLat = Math.min(...lats);
    const maxLat = Math.max(...lats);
    const minLng = Math.min(...lngs);
    const maxLng = Math.max(...lngs);

    const latRange = maxLat - minLat;
    const lngRange = maxLng - minLng;

    // Normalize coordinates to 0-1 range with padding
    return coords.map(coord => {
        // Normalize to 0-1
        let x = (coord.lng - minLng) / lngRange;
        let y = (coord.lat - minLat) / latRange;

        // Add padding (10% on each side)
        const padding = 0.1;
        x = padding + x * (1 - 2 * padding);
        y = padding + y * (1 - 2 * padding);

        // Flip Y axis (GPS lat increases northward, but canvas Y increases downward)
        y = 1 - y;

        return { x, y };
    });
}

/**
 * Get normalized track path from GPS coordinates
 */
export const trackPath = gpsToNormalized(trackGPSData);

/**
 * Calculate position on track at progress (0-1)
 * Uses linear interpolation between GPS points
 */
export function getPositionOnTrack(progress: number): {
    x: number;
    y: number;
    angle: number;
} {
    const totalPoints = trackPath.length;
    const position = progress * (totalPoints - 1);
    const index = Math.floor(position);
    const fraction = position - index;

    // Handle end of track
    if (index >= totalPoints - 1) {
        const last = trackPath[totalPoints - 1];
        const first = trackPath[0];
        const dx = first.x - last.x;
        const dy = first.y - last.y;
        return { ...last, angle: Math.atan2(dy, dx) };
    }

    // Get current and next point
    const current = trackPath[index];
    const next = trackPath[index + 1];

    // Linear interpolation
    const x = current.x + (next.x - current.x) * fraction;
    const y = current.y + (next.y - current.y) * fraction;

    // Calculate angle based on direction to next point
    const dx = next.x - current.x;
    const dy = next.y - current.y;
    const angle = Math.atan2(dy, dx);

    return { x, y, angle };
}

/**
 * Draw track on canvas
 */
export function drawTrack(
    ctx: CanvasRenderingContext2D,
    width: number,
    height: number,
    padding: number = 60,
    zoom: number = 1
): void {
    const w = width;
    const h = height;

    // Draw track outline (thicker gray line)
    // Scale width inversely with zoom for better detail when zoomed in
    ctx.strokeStyle = 'rgba(255, 255, 255, 0.2)';
    ctx.lineWidth = 40 / zoom;
    ctx.lineCap = 'round';
    ctx.lineJoin = 'round';

    ctx.beginPath();
    trackPath.forEach((point, i) => {
        const x = padding + point.x * (w - padding * 2);
        const y = padding + point.y * (h - padding * 2);

        if (i === 0) {
            ctx.moveTo(x, y);
        } else {
            ctx.lineTo(x, y);
        }
    });
    ctx.closePath();
    ctx.stroke();

    // Draw racing line (red dashed line)
    ctx.strokeStyle = 'rgba(220, 0, 0, 0.6)';
    ctx.lineWidth = 3 / zoom;
    ctx.setLineDash([10 / zoom, 5 / zoom]);

    ctx.beginPath();
    trackPath.forEach((point, i) => {
        const x = padding + point.x * (w - padding * 2);
        const y = padding + point.y * (h - padding * 2);

        if (i === 0) {
            ctx.moveTo(x, y);
        } else {
            ctx.lineTo(x, y);
        }
    });
    ctx.closePath();
    ctx.stroke();
    ctx.setLineDash([]);

    // Draw GPS coordinate points (small dots)
    ctx.fillStyle = 'rgba(255, 255, 255, 0.3)';
    trackPath.forEach(point => {
        const x = padding + point.x * (w - padding * 2);
        const y = padding + point.y * (h - padding * 2);
        ctx.beginPath();
        ctx.arc(x, y, 2, 0, Math.PI * 2);
        ctx.fill();
    });

    // Draw start/finish line
    const startX = padding + trackPath[0].x * (w - padding * 2);
    const startY = padding + trackPath[0].y * (h - padding * 2);

    ctx.strokeStyle = 'rgba(220, 0, 0, 0.8)';
    ctx.lineWidth = 4;
    ctx.beginPath();
    ctx.moveTo(startX - 20, startY);
    ctx.lineTo(startX + 20, startY);
    ctx.stroke();
}

/**
 * Draw bike on canvas
 */
export function drawBike(
    ctx: CanvasRenderingContext2D,
    x: number,
    y: number,
    angle: number,
    width: number,
    height: number,
    padding: number = 60,
    zoom: number = 1
): void {
    const canvasX = padding + x * (width - padding * 2);
    const canvasY = padding + y * (height - padding * 2);

    // Bike glow effect (scale with zoom)
    ctx.shadowBlur = 15 / zoom;
    ctx.shadowColor = 'rgba(220, 0, 0, 0.8)';

    // Draw bike circle (scale with zoom)
    ctx.fillStyle = '#dc0000';
    ctx.beginPath();
    ctx.arc(canvasX, canvasY, 12 / zoom, 0, Math.PI * 2);
    ctx.fill();

    // Direction line (scale with zoom)
    ctx.strokeStyle = '#ffffff';
    ctx.lineWidth = 3 / zoom;
    ctx.beginPath();
    ctx.moveTo(canvasX, canvasY);
    ctx.lineTo(canvasX + Math.cos(angle) * (20 / zoom), canvasY + Math.sin(angle) * (20 / zoom));
    ctx.stroke();

    ctx.shadowBlur = 0;
}

/**
 * Get GPS coordinate at progress (0-1) on track
 */
export function getGPSAtProgress(progress: number): GPSCoordinate {
    const totalPoints = trackGPSData.length;
    const position = progress * (totalPoints - 1);
    const index = Math.floor(position);
    const fraction = position - index;

    // Handle end of track
    if (index >= totalPoints - 1) {
        return trackGPSData[totalPoints - 1];
    }

    // Get current and next point
    const current = trackGPSData[index];
    const next = trackGPSData[index + 1];

    // Linear interpolation
    return {
        lat: current.lat + (next.lat - current.lat) * fraction,
        lng: current.lng + (next.lng - current.lng) * fraction,
    };
}
